#include <iostream>

/**
 * Рекурсивное решение задачи о Ханойских башнях (перекладывание N ингредиентов саба).
 *
 * Параметры:
 * - n: количество верхних ингредиентов, которые нужно переложить (они же — номера от 1 до n).
 * - from: номер исходной салфетки (откуда перекладываем).
 * - to: номер целевой салфетки (куда нужно переложить всю башню из n ингредиентов).
 * - aux: номер вспомогательной салфетки (временно свободной).
 */
void hanoi(int n, int from, int to, int aux) {
    if (n == 0) {
        return; // Базовый случай: 0 ингредиентов перекладывать не нужно
    }

    // 1. Перекладываем n - 1 верхних (меньших) ингредиентов с салфетки 'from' на вспомогательную 'aux',
    //    используя 'to' как временную салфетку.
    hanoi(n - 1, from, aux, to);

    // 2. Перекладываем самый большой из оставшихся (ингредиент с номером n)
    //    напрямую с салфетки 'from' на целевую салфетку 'to'.
    std::cout << "Ingredient " << n << " move from " << from << " to " << to << "\n";

    // 3. Перекладываем n - 1 ингредиентов со вспомогательной салфетки 'aux'
    //    поверх ингредиента n на целевую салфетку 'to', используя 'from' как временную.
    hanoi(n - 1, aux, to, from);
}

int main() {
    int n;
    std::cin >> n;
    hanoi(n, 1, 3, 2);
    return 0;
}